import { readFile, readdir, mkdir, writeFile, unlink } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { JSDOM } from 'jsdom';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'assets/icons/icons.svg');
const output = resolve(root, 'src/icons/generated');
const banner = '// Generated by npm run generate:icons. Do not edit.\n';
const componentName = name => name.split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('') + 'Icon';
const attrName = name => name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const tags = new Set(['path', 'rect', 'circle', 'ellipse', 'line', 'polyline', 'polygon', 'g', 'defs', 'mask', 'clipPath', 'use']);

export function generateIcons(text) {
  const dom = new JSDOM(text, { contentType: 'image/svg+xml' });
  const rootElement = dom.window.document.documentElement;
  if (rootElement.localName !== 'svg') throw new Error('Expected SVG root');
  const files = new Map(), names = new Set(), exports = new Set();
  for (const symbol of rootElement.children) {
    const name = symbol.getAttribute('id');
    if (symbol.localName !== 'symbol' || !/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name || '') || names.has(name)) throw new Error(`Invalid or duplicate symbol: ${name}`);
    names.add(name);
    const component = componentName(name);
    if (exports.has(component)) throw new Error(`Component name collision: ${component}`);
    exports.add(component);
    const nodes = [...symbol.querySelectorAll('*')];
    const ids = nodes.filter(node => node.hasAttribute('id')).map(node => node.getAttribute('id'));
    if (new Set(ids).size !== ids.length) throw new Error(`Duplicate drawing ID: ${name}`);
    const attributes = (node, isSymbol = false) => [...node.attributes].filter(a => !(isSymbol && a.name === 'id')).map(({ name: attr, value }) => {
      if (/^on/i.test(attr) || attr === 'style' || attr.includes(':')) throw new Error(`Unsupported attribute ${attr} in ${name}`);
      const refs = [...value.matchAll(/url\(\s*['"]?#([^\s)'";]+)['"]?\s*\)/g)].map(match => match[1]);
      if (attr === 'href') {
        if (!value.startsWith('#')) throw new Error(`External reference in ${name}`);
        refs.push(value.slice(1));
      }
      for (const id of refs) if (!ids.includes(id)) throw new Error(`Missing ID ${id} in ${name}`);
      let expression = JSON.stringify(value);
      if (attr === 'id') expression = `instanceId + '-' + ${expression}`;
      else for (const id of new Set(refs)) expression += `.split(${JSON.stringify('#' + id)}).join('#' + instanceId + '-' + ${JSON.stringify(id)})`;
      return `${attrName(attr)}={${expression}}`;
    }).join(' ');
    const render = node => {
      if (!tags.has(node.localName)) throw new Error(`Unsupported SVG element ${node.localName} in ${name}`);
      const attrs = attributes(node), children = [...node.children].map(render).join('');
      return `<${node.localName}${attrs ? ' ' + attrs : ''}${children ? `>${children}</${node.localName}>` : ' />'}`;
    };
    const attrs = attributes(symbol, true);
    const children = [...symbol.children].map(render).join('');
    const body = `${ids.length ? 'const instanceId = React.useId(); ' : ''}return <SvgIcon ${attrs} {...props} ref={ref}>${children}</SvgIcon>;`;
    files.set(`${component}.tsx`, `${banner}import * as React from 'react';\nimport { SvgIcon, type SvgIconProps } from '../svg-icon';\nexport const ${component} = /*#__PURE__*/ React.forwardRef<SVGSVGElement, SvgIconProps>(function ${component}(props, ref) { ${body} });\n`);
  }
  if (!names.size) throw new Error('Sprite has no symbols');
  files.set('index.ts', banner + [...exports].sort().map(name => `export { ${name} } from './${name}';`).join('\n') + '\n');
  dom.window.close();
  return files;
}

async function main() {
  const files = generateIcons(await readFile(source, 'utf8'));
  const check = process.argv.includes('--check');
  await mkdir(output, { recursive: true });
  const existing = await readdir(output), stale = [];
  for (const [name, content] of files) {
    const file = resolve(output, name);
    if (await readFile(file, 'utf8').catch(() => null) !== content) {
      stale.push(name);
      if (!check) await writeFile(file, content);
    }
  }
  for (const name of existing) if (!files.has(name)) {
    const file = resolve(output, name);
    if (!(await readFile(file, 'utf8')).startsWith(banner)) throw new Error(`Refusing to remove non-generated file: ${name}`);
    stale.push(name);
    if (!check) await unlink(file);
  }
  if (check && stale.length) throw new Error(`Generated icons are stale: ${stale.join(', ')}`);
  console.log(`${check ? 'Checked' : 'Generated'} ${files.size - 1} icons`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await main();
